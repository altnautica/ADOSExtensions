def _fc_time_usec(clock_align: "ClockAlign | None") -> int:
    """Resolve the FC-clock timestamp in microseconds for an emit call."""
    mono_ns = time.monotonic_ns()
    if clock_align is None:
        return mono_ns // 1000
    return clock_align.convert_to_fc_clock(mono_ns) // 1000


async def emit_optical_flow(
    ctx: "object",
    *,
    component_id: int,
    sensor_id: int,
    flow_x: int,
    flow_y: int,
    flow_comp_m_x: float,
    flow_comp_m_y: float,
    quality: int,
    ground_distance: float,
    clock_align: "ClockAlign | None" = None,
    flow_rate_x: float = 0.0,
    flow_rate_y: float = 0.0,
    sys_id: int = DEFAULT_SYS_ID,
) -> None:
    """Send one OPTICAL_FLOW message on the plugin's MAVLink component."""
    frame = build_optical_flow(
        sys_id=sys_id,
        comp_id=component_id,
        seq=_seq.next(),
        time_usec=_fc_time_usec(clock_align),
        sensor_id=sensor_id,
        flow_x=flow_x,
        flow_y=flow_y,
        flow_comp_m_x=flow_comp_m_x,
        flow_comp_m_y=flow_comp_m_y,
        quality=quality,
        ground_distance=ground_distance,
        flow_rate_x=flow_rate_x,
        flow_rate_y=flow_rate_y,
    )
    await _send(ctx, frame, component_id)


