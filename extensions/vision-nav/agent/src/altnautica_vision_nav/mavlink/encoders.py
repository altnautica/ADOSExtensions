async def emit_distance_sensor(
    ctx: "object",
    *,
    component_id: int,
    min_distance_cm: int,
    max_distance_cm: int,
    current_distance_cm: int,
    sensor_type: int,
    sensor_id: int,
    orientation: int,
    covariance: int,
    horizontal_fov: float = 0.0,
    vertical_fov: float = 0.0,
    quaternion: Sequence[float] = (0.0, 0.0, 0.0, 0.0),
    signal_quality: int = 0,
    clock_align: "ClockAlign | None" = None,
    time_boot_ms: int | None = None,
    sys_id: int = DEFAULT_SYS_ID,
) -> None:
    """Send one DISTANCE_SENSOR message on the plugin's MAVLink component.

    ``time_boot_ms`` may be supplied directly; otherwise it is derived
    from the time-sync offset converted to milliseconds. DISTANCE_SENSOR
    uses a millisecond uint32, not the microsecond uint64 of OPTICAL_FLOW.
    """
    if time_boot_ms is None:
        time_boot_ms = _fc_time_usec(clock_align) // 1000
    frame = build_distance_sensor(
        sys_id=sys_id,
        comp_id=component_id,
        seq=_seq.next(),
        time_boot_ms=time_boot_ms,
        min_distance_cm=min_distance_cm,
        max_distance_cm=max_distance_cm,
        current_distance_cm=current_distance_cm,
        sensor_type=sensor_type,
        sensor_id=sensor_id,
        orientation=orientation,
        covariance=covariance,
        horizontal_fov=horizontal_fov,
        vertical_fov=vertical_fov,
        quaternion=quaternion,
        signal_quality=signal_quality,
    )
    await _send(ctx, frame, component_id)


async def _send(ctx: "object", frame: bytes, component_id: int) -> None:
    """Dispatch a framed message on the plugin context's MAVLink facade.

    Tolerates either a real :class:`PluginContext` (async ``ctx.mavlink.send``)
    or a test double that records calls synchronously.
    """
    mavlink = getattr(ctx, "mavlink", None)
    if mavlink is None:
        log.warning("emit dropped: ctx.mavlink missing")
        return
    send = getattr(mavlink, "send", None)
    if send is None:
        log.warning("emit dropped: ctx.mavlink.send missing")
        return
    try:
        result = send(frame, component_id=component_id)
        if asyncio.iscoroutine(result):
            await result
    except Exception as exc:  # noqa: BLE001
        log.warning("emit failed: %s", exc)


