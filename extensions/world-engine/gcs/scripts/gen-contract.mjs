#!/usr/bin/env node
// Generate the TypeScript types of the capture contract (`ados.capture/1`)
// from the MIT schema files in `../contract/`:
//   - JSON Schemas -> `schema.ts` (json-schema-to-typescript), one declaration
//     per definition, the same definition set the Rust crate generates;
//   - protobuf -> `ados/capture/v1/*.ts` (ts-proto, types only, compiled by
//     buf so no system protoc is needed).
//
// Usage: node scripts/gen-contract.mjs [--out <dir>]
// Default output: src/lib/contract/generated/ (committed). The freshness test
// regenerates into a temp dir and compares.

import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const require = createRequire(import.meta.url);
const gcsDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contractDir = resolve(gcsDir, "../contract");
const BANNER = "// Generated by scripts/gen-contract.mjs from the capture contract. Do not edit.";

// Value constraints the TS types do not express (validation stays with the
// schema files), mirroring the Rust generator.
const STRIPPED = new Set([
  "pattern", "minLength", "maxLength", "minimum", "maximum", "exclusiveMinimum",
  "exclusiveMaximum", "if", "then", "else", "allOf", "$schema", "$id", "format",
]);

function rewriteRef(ref, titles) {
  const [file, frag = ""] = ref.split("#");
  if (frag.startsWith("/$defs/")) return `#/definitions/${frag.slice("/$defs/".length)}`;
  if (frag === "" && titles.has(file)) return `#/definitions/${titles.get(file)}`;
  throw new Error(`unsupported $ref ${ref}`);
}

// `isMap` marks a name -> schema map (`properties`, `definitions`), whose keys
// are field or type names, never keywords.
function structural(value, titles, isMap = false) {
  if (Array.isArray(value)) return value.map((v) => structural(v, titles));
  if (value === null || typeof value !== "object") return value;
  const out = {};
  for (const [k, v] of Object.entries(value)) {
    if (!isMap && STRIPPED.has(k)) continue;
    if (!isMap && k === "$ref") out[k] = rewriteRef(v, titles);
    else out[k] = structural(v, titles, !isMap && (k === "properties" || k === "definitions"));
  }
  return out;
}

async function genSchema(outDir) {
  const schemaDir = join(contractDir, "schema");
  const files = readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort();
  const docs = files.map((f) => [f, JSON.parse(readFileSync(join(schemaDir, f), "utf8"))]);
  const titles = new Map(docs.map(([f, d]) => [f, d.title]));
  const defs = {};
  for (const [, doc] of docs) {
    const { $defs = {}, ...main } = doc;
    for (const [name, def] of [...Object.entries($defs), [doc.title, main]]) {
      if (defs[name]) throw new Error(`duplicate definition ${name}`);
      defs[name] = { ...def, title: name };
    }
  }
  const definitions = structural(defs, titles, true);
  const parts = [];
  for (const name of Object.keys(definitions).sort()) {
    const ts = await compile({ ...definitions[name], definitions }, name, {
      bannerComment: "",
      declareExternallyReferenced: false,
      additionalProperties: false,
      ignoreMinAndMaxItems: true,
      unknownAny: true,
      strictIndexSignatures: true,
      format: true,
    });
    parts.push(ts.trim());
  }
  writeFileSync(join(outDir, "schema.ts"), `${BANNER}\n\n${parts.join("\n\n")}\n`);
}

function genProto(outDir) {
  const buf = require.resolve("@bufbuild/buf/bin/buf");
  const plugin = require.resolve("ts-proto/protoc-gen-ts_proto");
  const template = {
    version: "v2",
    plugins: [
      {
        local: [process.execPath, plugin],
        out: outDir,
        opt: ["onlyTypes=true", "snakeToCamel=false", "forceLong=bigint", "esModuleInterop=true"],
      },
    ],
  };
  execFileSync(
    process.execPath,
    [buf, "generate", join(contractDir, "proto"), "--template", JSON.stringify(template)],
    { cwd: gcsDir, stdio: ["ignore", "inherit", "inherit"] },
  );
}

function listTs(dir, prefix = "") {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? listTs(join(dir, e.name), `${prefix}${e.name}/`) : [`${prefix}${e.name}`],
  );
}

function genIndex(outDir) {
  const modules = listTs(outDir)
    .filter((f) => f.endsWith(".ts") && f !== "index.ts")
    .map((f) => f.replace(/\.ts$/, ""))
    .sort();
  // Protobuf modules each export the same `protobufPackage`/`protobufFileName`
  // constants, so each is re-exported under its own namespace.
  const lines = modules.map((m) =>
    m === "schema" ? `export * from "./${m}";` : `export * as ${m.split("/").pop()} from "./${m}";`,
  );
  writeFileSync(join(outDir, "index.ts"), `${BANNER}\n\n${lines.join("\n")}\n`);
}

export async function generate(outDir) {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  await genSchema(outDir);
  genProto(outDir);
  genIndex(outDir);
}

const outFlag = process.argv.indexOf("--out");
const outDir =
  outFlag >= 0 ? resolve(process.argv[outFlag + 1]) : join(gcsDir, "src/lib/contract/generated");
await generate(outDir);
