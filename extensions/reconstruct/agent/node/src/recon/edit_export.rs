//! The editor's delivery side: an export with its manifest, the predicted size
//! of an export or decimation, and an export-grade volume measurement, all on
//! the full-resolution cloud.
//!
//! A product sits in its session's local ENU frame, anchored to WGS-84 when
//! the session was georeferenced. An export keeps that frame (the inherited
//! one) or converts exactly to WGS-84 ECEF (EPSG:4978); the node never
//! reprojects to a map projection, so it never claims a CRS it did not write.

use std::fs;
use std::io::{BufWriter, Write};
use std::path::Path;

use ados_capture_contract::{ArtifactDescriptor, GeoAnchor};
use ados_mapping_protocol::edit::{
    point_in_polygon, DecimateTarget, EditOp, EditRecord, ExportFormat,
};

use super::edit::{write_atomic, Loaded};
use super::edit_ops::{self, Cancelled, Layered};
use super::StageError;
use crate::products::cloud::{self, PointCloud};
use crate::products::geo::enu_to_ecef;

/// The only CRS the node converts to.
pub const ECEF: &str = "EPSG:4978";
/// Points the LAZ size estimate compresses as a sample.
const SIZE_SAMPLE: usize = 200_000;

/// The anchor of a product artifact (its `.place.json` sidecar).
pub fn anchor_of(product: &Path, rel: &str) -> Option<GeoAnchor> {
    let b = fs::read(product.join(format!("{rel}.place.json"))).ok()?;
    serde_json::from_slice::<ArtifactDescriptor>(&b)
        .ok()?
        .anchor
}

/// The frame an artifact's coordinates are in, as provenance names it.
pub fn frame_label(product: &Path, rel: &str) -> Option<String> {
    anchor_of(product, rel).map(|a| {
        format!(
            "local ENU at {:.7}, {:.7}, {:.2} m (WGS-84)",
            a.lat_deg, a.lon_deg, a.h_ellipsoid_m
        )
    })
}

/// The CRS an export writes, and the label its manifest records.
fn resolve_crs(
    anchor: Option<&GeoAnchor>,
    chosen: Option<&str>,
    frame: Option<&str>,
) -> Result<String, StageError> {
    match (chosen, anchor) {
        (None, _) => Ok(match frame {
            Some(f) => format!("inherited: {f}"),
            None => "site-local frame".into(),
        }),
        (Some(c), Some(_)) if c.eq_ignore_ascii_case(ECEF) => Ok(ECEF.into()),
        (Some(c), None) if c.eq_ignore_ascii_case(ECEF) => Err(StageError::input(
            "This product has no georeference, so it exports in its site-local frame only.",
        )),
        (Some(c), _) => Err(StageError::input(format!(
            "The node exports in the product's own frame or in {ECEF} (ECEF); it does not reproject to {c}."
        ))),
    }
}

/// The header of a binary little-endian PLY of `n` points: double xyz, and
/// 8-bit RGB with colour.
fn ply_header(n: u64, color: bool) -> String {
    let rgb = if color {
        "property uchar red\nproperty uchar green\nproperty uchar blue\n"
    } else {
        ""
    };
    format!(
        "ply\nformat binary_little_endian 1.0\ncomment generated by reconstruct-node\nelement vertex {n}\nproperty double x\nproperty double y\nproperty double z\n{rgb}end_header\n"
    )
}

/// Bytes one PLY point takes.
fn ply_point_bytes(color: bool) -> u64 {
    24 + if color { 3 } else { 0 }
}

pub fn write_ply_points(path: &Path, c: &PointCloud) -> Result<(), StageError> {
    let mut w = BufWriter::new(fs::File::create(path)?);
    w.write_all(ply_header(c.points.len() as u64, c.colors.is_some()).as_bytes())?;
    for (i, p) in c.points.iter().enumerate() {
        for v in p {
            w.write_all(&v.to_le_bytes())?;
        }
        if let Some(col) = &c.colors {
            w.write_all(&col[i].map(|v| (v >> 8) as u8))?;
        }
    }
    w.flush()?;
    Ok(())
}

fn write_as(path: &Path, format: ExportFormat, data: &Layered) -> Result<(), StageError> {
    match format {
        ExportFormat::Laz => {
            cloud::write_laz_layers(path, &data.cloud, Some(&data.layers)).map_err(StageError::io)
        }
        ExportFormat::Ply => write_ply_points(path, &data.cloud),
    }
}

/// Write the current version as a delivery file plus its manifest under
/// `out/exports/`. The version's provenance is not touched: the manifest
/// carries it.
pub(super) fn export(
    product: &Path,
    cur: &Loaded,
    format: ExportFormat,
    crs: Option<&str>,
    decimate: Option<&DecimateTarget>,
    cancelled: &dyn Fn() -> bool,
) -> Result<EditRecord, StageError> {
    let anchor = anchor_of(product, &cur.edits.source);
    let crs_label = resolve_crs(anchor.as_ref(), crs, cur.edits.crs.as_deref())?;
    let mut data = match decimate {
        Some(t) => {
            edit_ops::decimate(&cur.data, t, cancelled)
                .map_err(|Cancelled| StageError::new("E_CANCELLED", "the job was cancelled"))?
                .0
        }
        None => cur.data.clone(),
    };
    if crs_label == ECEF {
        if let Some(a) = &anchor {
            for p in &mut data.cloud.points {
                *p = enu_to_ecef(a, *p);
            }
        }
    }
    let dir = product.join("out").join("exports");
    fs::create_dir_all(&dir)?;
    let stem = Path::new(&cur.rel)
        .file_stem()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_else(|| "cloud".into());
    let name = format!("{stem}.{}", format.extension());
    let tmp = dir.join(format!("{name}.tmp"));
    if let Err(e) = write_as(&tmp, format, &data) {
        let _ = fs::remove_file(&tmp);
        return Err(e);
    }
    if cancelled() {
        let _ = fs::remove_file(&tmp);
        return Err(StageError::new("E_CANCELLED", "the job was cancelled"));
    }
    fs::rename(&tmp, dir.join(&name))?;
    let bytes = fs::metadata(dir.join(&name))?.len();
    let manifest = serde_json::json!({
        "format": format,
        "crs": crs_label,
        "points": data.len(),
        "bytes": bytes,
        "product": cur.rel,
        "edited": cur.edits.edited,
        "edits": cur.edits,
    });
    write_atomic(
        &dir.join(format!("{stem}.manifest.json")),
        &serde_json::to_vec_pretty(&manifest)?,
    )?;
    Ok(EditRecord {
        op: EditOp::Export {
            format,
            crs: crs.map(str::to_string),
            decimate: decimate.copied(),
        },
        removed: decimate.map(|_| (cur.data.len() - data.len()) as u64),
        added: None,
        self_overlap: None,
        source_layers: Vec::new(),
        deviation_m: None,
        result: format!("out/exports/{name}"),
        ts: super::edit::now_rfc3339(),
    })
}

/// The predicted size of writing `rel` in `format`, after an optional
/// decimation: exact for PLY, and for LAZ the size of the first 200,000
/// points (decimated by the same ratio) compressed by this node's writer,
/// scaled to the count.
pub fn estimate_size(
    product: &Path,
    rel: &str,
    format: ExportFormat,
    decimate: Option<&DecimateTarget>,
) -> Result<(u64, u64), StageError> {
    let path = product.join(rel);
    let mut reader = las::Reader::from_path(&path).map_err(StageError::io)?;
    let total = reader.header().number_of_points();
    let has_color = reader.header().point_format().has_color;
    let points = decimate.map_or(total, |t| t.points_for(total));
    if format == ExportFormat::Ply {
        let header = ply_header(points, has_color).len() as u64;
        return Ok((points, header + points * ply_point_bytes(has_color)));
    }
    let data = reader
        .read_points(SIZE_SAMPLE as u64)
        .map_err(StageError::io)?;
    let mut sample = Layered {
        cloud: PointCloud {
            points: data
                .x()
                .zip(data.y())
                .zip(data.z())
                .map(|((x, y), z)| [x, y, z])
                .collect(),
            colors: data.rgb().map(|it| it.map(|(r, g, b)| [r, g, b]).collect()),
        },
        layers: data.point_source_id().collect(),
    };
    if sample.is_empty() {
        return Ok((0, 0));
    }
    if decimate.is_some() {
        let ratio = points as f64 / total.max(1) as f64;
        let target = DecimateTarget {
            target_points: Some(((sample.len() as f64) * ratio).round().max(1.0) as u64),
            target_percent: None,
        };
        sample = edit_ops::decimate(&sample, &target, &|| false)
            .map_err(|Cancelled| StageError::new("E_CANCELLED", "the job was cancelled"))?
            .0;
    }
    let size = |c: &Layered| -> Result<u64, StageError> {
        Ok(cloud::laz_bytes(&c.cloud, Some(&c.layers))
            .map_err(StageError::io)?
            .len() as u64)
    };
    let empty = Layered {
        cloud: PointCloud {
            points: Vec::new(),
            colors: sample.cloud.colors.as_ref().map(|_| Vec::new()),
        },
        layers: Vec::new(),
    };
    let (full, base) = (size(&sample)?, size(&empty)?);
    let per_point = full.saturating_sub(base) as f64 / sample.len() as f64;
    Ok((points, base + (per_point * points as f64).round() as u64))
}

/// Volume of the cloud above a horizontal base plane inside a ground
/// polygon: per `cell_m` grid cell, the highest point above the plane times
/// the cell area. Returns the volume (m³) and the cells that held points.
pub fn volume_above(
    cloud: &PointCloud,
    polygon: &[[f64; 2]],
    base_z: f64,
    cell_m: f64,
) -> (f64, u64) {
    let mut top: std::collections::HashMap<(i64, i64), f64> = std::collections::HashMap::new();
    for p in &cloud.points {
        if !point_in_polygon(polygon, [p[0], p[1]]) {
            continue;
        }
        let key = (
            (p[0] / cell_m).floor() as i64,
            (p[1] / cell_m).floor() as i64,
        );
        let e = top.entry(key).or_insert(f64::NEG_INFINITY);
        *e = e.max(p[2]);
    }
    let vol = top.values().map(|z| (z - base_z).max(0.0)).sum::<f64>() * cell_m * cell_m;
    (vol, top.len() as u64)
}

